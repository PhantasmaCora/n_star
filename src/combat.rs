








#[derive(Clone)]
pub struct MeleeAttackSpec {
    pub pen_rating: i32,
    pub damage_die: String,
    pub technique_rating: i32
}

pub fn map_penetration(rating: i32) -> [f32; 4] {
    match rating {
        -3 => [0.125, 0.0, 0.0, 0.0],
        -2 => [0.25, 0.01, 0.0, 0.0],
        -1 => [0.5, 0.05, 0.0, 0.0],
        0 => [0.75, 0.1, 0.01, 0.0],
        1 => [0.8, 0.25, 0.05, 0.0],
        2 => [0.9, 0.4, 0.1, 0.005],
        3 => [0.95, 0.5, 0.2, 0.01],
        4 => [0.96, 0.6, 0.3, 0.05],
        5 => [0.98, 0.7, 0.4, 0.1],
        6 => [0.99, 0.8, 0.5, 0.2],
        7 => [0.999, 0.85, 0.55, 0.25],
        x if x > 7 => [1.0, 0.875, 0.6, 0.3],
        _ => [0.1, 0.0, 0.0, 0.0]
    }

}
